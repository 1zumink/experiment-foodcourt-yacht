export const plural = (n: number, lang: Lang, ru: [string, string, string], en: [string, string]) => {
  if (lang === 'en') return n === 1 ? en[0] : en[1];
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return ru[0];
  if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) return ru[1];
  return ru[2];
};

export const money = (n: number) => `${Math.round(n).toLocaleString('ru-RU')} ₽`;
